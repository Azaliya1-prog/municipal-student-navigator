PRAGMA foreign_keys = ON;

DROP TABLE IF EXISTS "Отклики";
DROP TABLE IF EXISTS "Документы_портфолио";
DROP TABLE IF EXISTS "Портфолио";
DROP TABLE IF EXISTS "Вакансии";
DROP TABLE IF EXISTS "Муниципальные_органы";
DROP TABLE IF EXISTS "Студенты";
DROP TABLE IF EXISTS "Пользователи";
DROP TABLE IF EXISTS "Главное_меню";

CREATE TABLE "Пользователи" (
    "id" INTEGER PRIMARY KEY AUTOINCREMENT,
    "имя" TEXT NOT NULL,
    "email" TEXT NOT NULL UNIQUE,
    "пароль" TEXT NOT NULL,
    "роль" TEXT NOT NULL DEFAULT 'student',
    "дата_регистрации" TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE "Студенты" (
    "id" INTEGER PRIMARY KEY AUTOINCREMENT,
    "id_пользователя" INTEGER NOT NULL UNIQUE,
    "ФИО" TEXT NOT NULL,
    "ВУЗ" TEXT,
    "направление" TEXT,
    "курс" TEXT,
    "email" TEXT NOT NULL,
    "телефон" TEXT,
    FOREIGN KEY ("id_пользователя") REFERENCES "Пользователи"("id") ON DELETE CASCADE
);

CREATE TABLE "Портфолио" (
    "id" INTEGER PRIMARY KEY AUTOINCREMENT,
    "id_студента" INTEGER NOT NULL UNIQUE,
    "описание" TEXT,
    "навыки" TEXT,
    "достижения" TEXT,
    "ссылка_на_резюме" TEXT,
    "дата_обновления" TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP,
    FOREIGN KEY ("id_студента") REFERENCES "Студенты"("id") ON DELETE CASCADE
);

CREATE TABLE "Документы_портфолио" (
    "id" INTEGER PRIMARY KEY AUTOINCREMENT,
    "id_студента" INTEGER NOT NULL,
    "имя_файла" TEXT NOT NULL,
    "исходное_имя" TEXT NOT NULL,
    "дата_загрузки" TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP,
    FOREIGN KEY ("id_студента") REFERENCES "Студенты"("id") ON DELETE CASCADE
);

CREATE TABLE "Муниципальные_органы" (
    "id" INTEGER PRIMARY KEY AUTOINCREMENT,
    "название" TEXT NOT NULL,
    "город" TEXT NOT NULL,
    "адрес" TEXT,
    "контактное_лицо" TEXT
);

CREATE TABLE "Вакансии" (
    "id" INTEGER PRIMARY KEY AUTOINCREMENT,
    "id_органа" INTEGER NOT NULL,
    "название" TEXT NOT NULL,
    "требования" TEXT,
    "условия" TEXT,
    "изображение" TEXT NOT NULL DEFAULT 'media.svg',
    "дата_публикации" TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP,
    "активна" INTEGER NOT NULL DEFAULT 1,
    FOREIGN KEY ("id_органа") REFERENCES "Муниципальные_органы"("id") ON DELETE CASCADE
);

CREATE TABLE "Отклики" (
    "id" INTEGER PRIMARY KEY AUTOINCREMENT,
    "id_студента" INTEGER NOT NULL,
    "id_вакансии" INTEGER NOT NULL,
    "ФИО_анкеты" TEXT NOT NULL,
    "email_анкеты" TEXT NOT NULL,
    "телефон_анкеты" TEXT,
    "ВУЗ_анкеты" TEXT,
    "направление_анкеты" TEXT,
    "курс_анкеты" TEXT,
    "сопроводительное_письмо" TEXT,
    "дата_отклика" TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP,
    "статус" TEXT NOT NULL DEFAULT 'Отправлен',
    FOREIGN KEY ("id_студента") REFERENCES "Студенты"("id") ON DELETE CASCADE,
    FOREIGN KEY ("id_вакансии") REFERENCES "Вакансии"("id") ON DELETE CASCADE,
    UNIQUE ("id_студента", "id_вакансии")
);

CREATE TABLE "Главное_меню" (
    "id" INTEGER PRIMARY KEY AUTOINCREMENT,
    "название" TEXT NOT NULL,
    "ссылка" TEXT NOT NULL,
    "роль" TEXT NOT NULL DEFAULT 'all',
    "порядок" INTEGER NOT NULL DEFAULT 0
);

